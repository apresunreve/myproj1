#!/usr/bin/env bash
# Baboonland clip-level video training via SlowFast (X3D / I3D).
# Mirrors scripts/run_kabr_clip_video_train.sh but points at the baboonland
# manifests and sets MODEL.NUM_CLASSES=13. Reuses the SlowFast `kabr_clips`
# dataset loader, which is dataset-agnostic (reads manifest JSONL + classes.json).
#
# Model keys: x3d-xs | x3d-s | x3d-m | x3d-l | i3d-l
set -euo pipefail

if [ "$#" -ne 1 ]; then
  echo "Usage: $0 <x3d-xs|x3d-s|x3d-m|x3d-l|i3d-l>"
  exit 1
fi

MODEL_KEY=$1

SLOWFAST_ROOT=${SLOWFAST_ROOT:-/scratch/general/vast/j.yan/SlowFast}
CLIP_MANIFEST_DIR=${CLIP_MANIFEST_DIR:-/scratch/general/vast/j.yan/myproj1/baboonland_files/annotation/clip_manifests}
IMAGE_ROOT=${IMAGE_ROOT:-/scratch/general/nfs1/u1320844/baboon2/charades/dataset/image}
CLASSES_PATH=${CLASSES_PATH:-/scratch/general/nfs1/u1320844/baboon2/charades/annotation/classes.json}
NUM_CLASSES=${NUM_CLASSES:-13}
PY=${PYTHON_BIN:-/uufs/chpc.utah.edu/common/home/u1320844/miniconda3/bin/python}

NUM_GPUS=${NUM_GPUS:-1}
NUM_SHARDS=${NUM_SHARDS:-1}
RNG_SEED=${RNG_SEED:-0}
MAX_EPOCH=${MAX_EPOCH:-120}
EVAL_PERIOD=${EVAL_PERIOD:-5}
CHECKPOINT_PERIOD=${CHECKPOINT_PERIOD:-5}
NUM_WORKERS=${NUM_WORKERS:-8}
LOG_MODEL_INFO=${LOG_MODEL_INFO:-False}
AUTO_RESUME=${AUTO_RESUME:-True}
TRAIN_MIXED_PRECISION=${TRAIN_MIXED_PRECISION:-False}

case "$MODEL_KEY" in
  x3d-xs)
    CFG_PATH=${CFG_PATH:-$SLOWFAST_ROOT/configs/Kinetics/X3D_XS.yaml}
    MODEL_NAME=${MODEL_NAME:-x3d_xs}
    TRAIN_BATCH_SIZE=${TRAIN_BATCH_SIZE:-16}
    TEST_BATCH_SIZE=${TEST_BATCH_SIZE:-8}
    BASE_LR=${BASE_LR:-0.0125}
    NUM_FRAMES=${NUM_FRAMES:-4}
    SAMPLING_RATE=${SAMPLING_RATE:-12}
    TRAIN_JITTER_SCALES=${TRAIN_JITTER_SCALES:-[182,228]}
    TRAIN_CROP_SIZE=${TRAIN_CROP_SIZE:-160}
    TEST_CROP_SIZE=${TEST_CROP_SIZE:-182}
    TEST_NUM_ENSEMBLE_VIEWS=${TEST_NUM_ENSEMBLE_VIEWS:-2}
    TEST_NUM_SPATIAL_CROPS=${TEST_NUM_SPATIAL_CROPS:-1}
    WIDTH_FACTOR=${WIDTH_FACTOR:-2.0}
    DEPTH_FACTOR=${DEPTH_FACTOR:-2.2}
    BOTTLENECK_FACTOR=${BOTTLENECK_FACTOR:-2.25}
    DIM_C1=${DIM_C1:-12}
    DIM_C5=${DIM_C5:-2048}
    ARCH_OPTS=(
      MODEL.ARCH x3d MODEL.MODEL_NAME X3D
      X3D.WIDTH_FACTOR "$WIDTH_FACTOR" X3D.DEPTH_FACTOR "$DEPTH_FACTOR"
      X3D.BOTTLENECK_FACTOR "$BOTTLENECK_FACTOR" X3D.DIM_C1 "$DIM_C1" X3D.DIM_C5 "$DIM_C5"
      RESNET.TRANS_FUNC x3d_transform RESNET.DEPTH 50
      RESNET.NUM_BLOCK_TEMP_KERNEL "[[3],[4],[6],[3]]"
      RESNET.SPATIAL_STRIDES "[[1],[2],[2],[2]]"
      RESNET.SPATIAL_DILATIONS "[[1],[1],[1],[1]]"
      RESNET.STRIDE_1X1 False RESNET.ZERO_INIT_FINAL_BN True RESNET.ZERO_INIT_FINAL_CONV False
    )
    ;;
  x3d-s)
    CFG_PATH=${CFG_PATH:-$SLOWFAST_ROOT/configs/Kinetics/X3D_S.yaml}
    MODEL_NAME=${MODEL_NAME:-x3d_s}
    TRAIN_BATCH_SIZE=${TRAIN_BATCH_SIZE:-8}
    TEST_BATCH_SIZE=${TEST_BATCH_SIZE:-4}
    BASE_LR=${BASE_LR:-0.0125}
    NUM_FRAMES=${NUM_FRAMES:-13}
    SAMPLING_RATE=${SAMPLING_RATE:-6}
    TRAIN_JITTER_SCALES=${TRAIN_JITTER_SCALES:-[182,228]}
    TRAIN_CROP_SIZE=${TRAIN_CROP_SIZE:-160}
    TEST_CROP_SIZE=${TEST_CROP_SIZE:-182}
    TEST_NUM_ENSEMBLE_VIEWS=${TEST_NUM_ENSEMBLE_VIEWS:-2}
    TEST_NUM_SPATIAL_CROPS=${TEST_NUM_SPATIAL_CROPS:-1}
    WIDTH_FACTOR=${WIDTH_FACTOR:-2.0}
    DEPTH_FACTOR=${DEPTH_FACTOR:-2.2}
    BOTTLENECK_FACTOR=${BOTTLENECK_FACTOR:-2.25}
    DIM_C1=${DIM_C1:-12}
    DIM_C5=${DIM_C5:-2048}
    ARCH_OPTS=(
      MODEL.ARCH x3d MODEL.MODEL_NAME X3D
      X3D.WIDTH_FACTOR "$WIDTH_FACTOR" X3D.DEPTH_FACTOR "$DEPTH_FACTOR"
      X3D.BOTTLENECK_FACTOR "$BOTTLENECK_FACTOR" X3D.DIM_C1 "$DIM_C1" X3D.DIM_C5 "$DIM_C5"
      RESNET.TRANS_FUNC x3d_transform RESNET.DEPTH 50
      RESNET.NUM_BLOCK_TEMP_KERNEL "[[3],[4],[6],[3]]"
      RESNET.SPATIAL_STRIDES "[[1],[2],[2],[2]]"
      RESNET.SPATIAL_DILATIONS "[[1],[1],[1],[1]]"
      RESNET.STRIDE_1X1 False RESNET.ZERO_INIT_FINAL_BN True RESNET.ZERO_INIT_FINAL_CONV False
    )
    ;;
  x3d-m)
    CFG_PATH=${CFG_PATH:-$SLOWFAST_ROOT/configs/Kinetics/X3D_M.yaml}
    MODEL_NAME=${MODEL_NAME:-x3d_m}
    TRAIN_BATCH_SIZE=${TRAIN_BATCH_SIZE:-4}
    TEST_BATCH_SIZE=${TEST_BATCH_SIZE:-4}
    BASE_LR=${BASE_LR:-0.0125}
    NUM_FRAMES=${NUM_FRAMES:-16}
    SAMPLING_RATE=${SAMPLING_RATE:-5}
    TRAIN_JITTER_SCALES=${TRAIN_JITTER_SCALES:-[256,320]}
    TRAIN_CROP_SIZE=${TRAIN_CROP_SIZE:-224}
    TEST_CROP_SIZE=${TEST_CROP_SIZE:-256}
    TEST_NUM_ENSEMBLE_VIEWS=${TEST_NUM_ENSEMBLE_VIEWS:-2}
    TEST_NUM_SPATIAL_CROPS=${TEST_NUM_SPATIAL_CROPS:-1}
    WIDTH_FACTOR=${WIDTH_FACTOR:-2.0}
    DEPTH_FACTOR=${DEPTH_FACTOR:-2.2}
    BOTTLENECK_FACTOR=${BOTTLENECK_FACTOR:-2.25}
    DIM_C1=${DIM_C1:-12}
    DIM_C5=${DIM_C5:-2048}
    ARCH_OPTS=(
      MODEL.ARCH x3d MODEL.MODEL_NAME X3D
      X3D.WIDTH_FACTOR "$WIDTH_FACTOR" X3D.DEPTH_FACTOR "$DEPTH_FACTOR"
      X3D.BOTTLENECK_FACTOR "$BOTTLENECK_FACTOR" X3D.DIM_C1 "$DIM_C1" X3D.DIM_C5 "$DIM_C5"
      RESNET.TRANS_FUNC x3d_transform RESNET.DEPTH 50
      RESNET.NUM_BLOCK_TEMP_KERNEL "[[3],[4],[6],[3]]"
      RESNET.SPATIAL_STRIDES "[[1],[2],[2],[2]]"
      RESNET.SPATIAL_DILATIONS "[[1],[1],[1],[1]]"
      RESNET.STRIDE_1X1 False RESNET.ZERO_INIT_FINAL_BN True RESNET.ZERO_INIT_FINAL_CONV False
    )
    ;;
  x3d-l)
    # Matches scripts/run_x3d_l_gemma_baselines.sh settings on KABR
    CFG_PATH=${CFG_PATH:-$SLOWFAST_ROOT/configs/KABR/X3D_CLIP_LEVEL.yaml}
    MODEL_NAME=${MODEL_NAME:-x3d_l}
    TRAIN_BATCH_SIZE=${TRAIN_BATCH_SIZE:-4}
    TEST_BATCH_SIZE=${TEST_BATCH_SIZE:-4}
    BASE_LR=${BASE_LR:-0.0125}
    NUM_FRAMES=${NUM_FRAMES:-16}
    SAMPLING_RATE=${SAMPLING_RATE:-5}
    TRAIN_JITTER_SCALES=${TRAIN_JITTER_SCALES:-[300,300]}
    TRAIN_CROP_SIZE=${TRAIN_CROP_SIZE:-300}
    TEST_CROP_SIZE=${TEST_CROP_SIZE:-300}
    TEST_NUM_ENSEMBLE_VIEWS=${TEST_NUM_ENSEMBLE_VIEWS:-2}
    TEST_NUM_SPATIAL_CROPS=${TEST_NUM_SPATIAL_CROPS:-1}
    WIDTH_FACTOR=${WIDTH_FACTOR:-2.0}
    DEPTH_FACTOR=${DEPTH_FACTOR:-5.0}
    BOTTLENECK_FACTOR=${BOTTLENECK_FACTOR:-2.25}
    DIM_C1=${DIM_C1:-12}
    DIM_C5=${DIM_C5:-2048}
    ARCH_OPTS=(
      MODEL.ARCH x3d MODEL.MODEL_NAME X3D
      X3D.WIDTH_FACTOR "$WIDTH_FACTOR" X3D.DEPTH_FACTOR "$DEPTH_FACTOR"
      X3D.BOTTLENECK_FACTOR "$BOTTLENECK_FACTOR" X3D.DIM_C1 "$DIM_C1" X3D.DIM_C5 "$DIM_C5"
      RESNET.TRANS_FUNC x3d_transform RESNET.DEPTH 50
      RESNET.NUM_BLOCK_TEMP_KERNEL "[[5],[10],[25],[15]]"
      RESNET.SPATIAL_STRIDES "[[1],[2],[2],[2]]"
      RESNET.SPATIAL_DILATIONS "[[1],[1],[1],[1]]"
      RESNET.STRIDE_1X1 False RESNET.ZERO_INIT_FINAL_BN True RESNET.ZERO_INIT_FINAL_CONV False
    )
    ;;
  i3d-l)
    CFG_PATH=${CFG_PATH:-$SLOWFAST_ROOT/configs/Kinetics/I3D_8x8_R101.yaml}
    MODEL_NAME=${MODEL_NAME:-i3d_l}
    TRAIN_BATCH_SIZE=${TRAIN_BATCH_SIZE:-4}
    TEST_BATCH_SIZE=${TEST_BATCH_SIZE:-4}
    BASE_LR=${BASE_LR:-0.0125}
    NUM_FRAMES=${NUM_FRAMES:-8}
    SAMPLING_RATE=${SAMPLING_RATE:-8}
    TRAIN_JITTER_SCALES=${TRAIN_JITTER_SCALES:-[256,320]}
    TRAIN_CROP_SIZE=${TRAIN_CROP_SIZE:-224}
    TEST_CROP_SIZE=${TEST_CROP_SIZE:-256}
    TEST_NUM_ENSEMBLE_VIEWS=${TEST_NUM_ENSEMBLE_VIEWS:-2}
    TEST_NUM_SPATIAL_CROPS=${TEST_NUM_SPATIAL_CROPS:-1}
    ARCH_OPTS=(
      MODEL.ARCH i3d MODEL.MODEL_NAME ResNet
      RESNET.DEPTH 101 RESNET.WIDTH_PER_GROUP 64 RESNET.NUM_GROUPS 1
      RESNET.TRANS_FUNC bottleneck_transform
      RESNET.STRIDE_1X1 False RESNET.ZERO_INIT_FINAL_BN True
      RESNET.NUM_BLOCK_TEMP_KERNEL "[[3],[4],[23],[3]]"
      NONLOCAL.LOCATION "[[[]],[[]],[[]],[[]]]"
      NONLOCAL.GROUP "[[1],[1],[1],[1]]"
      NONLOCAL.INSTANTIATION softmax
    )
    ;;
  *)
    echo "Unsupported model key: $MODEL_KEY"
    exit 1
    ;;
esac

OUT_ROOT_DEFAULT=/scratch/general/nfs1/u1320844/manual_train/baboonland_clip/$MODEL_NAME
OUT_ROOT=${OUT_ROOT:-$OUT_ROOT_DEFAULT}

for p in "$CLIP_MANIFEST_DIR/train.jsonl" "$CLIP_MANIFEST_DIR/val.jsonl" "$CLASSES_PATH" "$CFG_PATH"; do
  [ -f "$p" ] || { echo "Missing: $p"; exit 1; }
done
[ -d "$IMAGE_ROOT" ] || { echo "Missing image root: $IMAGE_ROOT"; exit 1; }
[ -f "$SLOWFAST_ROOT/slowfast/datasets/kabr_clips.py" ] || { echo "Missing kabr_clips loader"; exit 1; }

mkdir -p "$OUT_ROOT"
cd "$SLOWFAST_ROOT"
export PYTHONPATH="$SLOWFAST_ROOT"

echo "=== Baboonland clip training ==="
echo "Model key:       $MODEL_KEY"
echo "SlowFast root:   $SLOWFAST_ROOT"
echo "Config:          $CFG_PATH"
echo "Manifest dir:    $CLIP_MANIFEST_DIR"
echo "Image root:      $IMAGE_ROOT"
echo "Classes path:    $CLASSES_PATH"
echo "Num classes:     $NUM_CLASSES"
echo "Output dir:      $OUT_ROOT"
echo "Train batch:     $TRAIN_BATCH_SIZE"
echo "Frames:          $NUM_FRAMES"
echo "Epochs:          $MAX_EPOCH"

"$PY" tools/run_net.py \
  --cfg "$CFG_PATH" \
  --opts \
  TRAIN.ENABLE True \
  TRAIN.DATASET kabr_clips \
  TRAIN.BATCH_SIZE "$TRAIN_BATCH_SIZE" \
  TRAIN.EVAL_PERIOD "$EVAL_PERIOD" \
  TRAIN.CHECKPOINT_PERIOD "$CHECKPOINT_PERIOD" \
  TRAIN.AUTO_RESUME "$AUTO_RESUME" \
  TRAIN.MIXED_PRECISION "$TRAIN_MIXED_PRECISION" \
  TEST.ENABLE True \
  TEST.DATASET kabr_clips \
  TEST.BATCH_SIZE "$TEST_BATCH_SIZE" \
  TEST.NUM_ENSEMBLE_VIEWS "$TEST_NUM_ENSEMBLE_VIEWS" \
  TEST.NUM_SPATIAL_CROPS "$TEST_NUM_SPATIAL_CROPS" \
  TEST.SAVE_RESULTS_PATH clip_level/results.pkl \
  TEST.SAVE_CLIP_RESULTS_PATH clip_level/predictions.jsonl \
  DATA.PATH_TO_DATA_DIR "$CLIP_MANIFEST_DIR" \
  DATA.PATH_PREFIX "$IMAGE_ROOT" \
  DATA.NUM_FRAMES "$NUM_FRAMES" \
  DATA.SAMPLING_RATE "$SAMPLING_RATE" \
  DATA.TRAIN_JITTER_SCALES "$TRAIN_JITTER_SCALES" \
  DATA.TRAIN_CROP_SIZE "$TRAIN_CROP_SIZE" \
  DATA.TEST_CROP_SIZE "$TEST_CROP_SIZE" \
  DATA.INPUT_CHANNEL_NUM "[3]" \
  DATA.MULTI_LABEL False \
  DATA.ENSEMBLE_METHOD sum \
  MODEL.NUM_CLASSES "$NUM_CLASSES" \
  MODEL.LOSS_FUNC cross_entropy \
  MODEL.HEAD_ACT softmax \
  SOLVER.BASE_LR "$BASE_LR" \
  SOLVER.BASE_LR_SCALE_NUM_SHARDS False \
  SOLVER.MAX_EPOCH "$MAX_EPOCH" \
  NUM_GPUS "$NUM_GPUS" \
  NUM_SHARDS "$NUM_SHARDS" \
  RNG_SEED "$RNG_SEED" \
  DATA_LOADER.NUM_WORKERS "$NUM_WORKERS" \
  TENSORBOARD.CLASS_NAMES_PATH "$CLASSES_PATH" \
  OUTPUT_DIR "$OUT_ROOT" \
  LOG_MODEL_INFO "$LOG_MODEL_INFO" \
  "${ARCH_OPTS[@]}" \
  2>&1 | tee "$OUT_ROOT/train.log"

echo "=== Done ==="
echo "Train log: $OUT_ROOT/train.log"
echo "Output dir: $OUT_ROOT"
